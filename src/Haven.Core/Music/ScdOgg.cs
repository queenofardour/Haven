namespace Haven.Core.Music;

/// <summary>
/// Reads the Ogg Vorbis file inside a game SCD's only (or first) Vorbis audio entry, undoing the game's light scrambling.
/// Layout after VFXEditor (Formats/ScdFormat, MIT) and vgmstream (ISC): the entry's 0x20-byte header (data size,
/// channels, rate, format 6, loop, extra size, flags), then its Vorbis extra header: a version byte, its own size, an XOR
/// byte; at +0x10 the seek table's size and at +0x14 the Vorbis header's; the seek table, the Vorbis header packets, and
/// the audio pages. Version 2 XORs the Vorbis header with that byte; version 3 XORs the header and audio with a table keyed
/// by the audio's size; Haven's own SCDs (<see cref="ScdMusic"/>) are version 0, the headers left inside the audio.
/// </summary>
public static class ScdOgg
{
    public static byte[] Extract(byte[] scd)
    {
        if (scd.Length < 0x60 || !scd.AsSpan(0, 8).SequenceEqual("SEDBSSCF"u8)) throw new InvalidDataException("Not an SCD file.");
        int I32(long at) => at >= 0 && at + 4 <= scd.Length ? BitConverter.ToInt32(scd, (int)at) : throw new InvalidDataException("The SCD is cut short.");
        var tables = BitConverter.ToInt16(scd, 0x0E);
        var count = BitConverter.ToInt16(scd, tables + 4);
        var table = I32(tables + 12);
        for (var i = 0; i < count; i++)
        {
            long entry = I32(table + 4L * i);
            if (I32(entry + 12) != 6) continue;
            var size = I32(entry); var extraSize = I32(entry + 0x18);
            long extra = entry + 0x20, data = extra + extraSize;
            if (size <= 0 || extraSize < 0x20 || data + size > scd.Length) throw new InvalidDataException("The SCD's audio entry runs past its end.");
            var version = scd[extra]; var xor = scd[extra + 2];
            var seek = I32(extra + 0x10); var headerSize = I32(extra + 0x14);
            long header = extra + 0x20 + seek;
            if (seek < 0 || headerSize < 0 || header + headerSize > data) throw new InvalidDataException("The SCD's Vorbis header is out of place.");
            var ogg = new byte[headerSize + size];
            Array.Copy(scd, header, ogg, 0, headerSize);
            Array.Copy(scd, data, ogg, headerSize, size);
            if (version == 2 && xor != 0) for (var b = 0; b < headerSize; b++) ogg[b] ^= xor;
            else if (version == 3) Xor3(ogg, size);
            else if (version is not (0 or 2)) throw new InvalidDataException($"The SCD uses an unknown Vorbis encoding ({version}).");
            if (ogg.Length < 4 || !ogg.AsSpan(0, 4).SequenceEqual("OggS"u8)) throw new InvalidDataException("The SCD's audio isn't Ogg Vorbis.");
            return ogg;
        }
        throw new InvalidDataException("The SCD holds no Vorbis audio.");
    }

    /// <summary>
    /// Version 3's scrambling, which undoes itself: vgmstream's scd_ogg_v3_decryption_callback (table by Ioncannon),
    /// keyed by the audio's size, offsets counted from the Vorbis header's start, which is scrambled with the audio
    /// (checked on the game's files).
    /// </summary>
    public static void Xor3(Span<byte> stream, int audioSize)
    {
        byte byte1 = (byte)(audioSize & 0x7F), byte2 = (byte)(audioSize & 0x3F);
        for (var b = 0; b < stream.Length; b++) stream[b] ^= (byte)(V3Table[(byte2 + b) & 0xFF] ^ byte1);
    }

